"""Pack an OpenCV (CUDA) build that was installed into site-packages into a pip wheel.

Pure standard library, no setuptools/wheel needed.  The wheel contains:
  * the `cv2` package exactly as `cmake --target install` put it into site-packages
  * all OpenCV runtime DLLs, copied to `cv2/libs/`
  * a rewritten `cv2/config.py` / `cv2/config-X.Y.py` that is relocatable
    (no absolute C:/build paths)

CUDA Toolkit and cuDNN DLLs are NOT bundled. They are looked up at import time
via %CUDA_PATH%, %CUDNN_PATH% and the default NVIDIA install folders.

Usage:
  python make_wheel.py --cv2-dir <site-packages>\\cv2 --bin-dir <install>\\x64\\vc18\\bin ^
                       --out <dir> --version 4.14.0 --cuda 13.5
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import re
import sys
import zipfile
from pathlib import Path

DIST_NAME = "opencv-cuda-custom"
SUMMARY = "OpenCV (with contrib) custom build with CUDA support for Windows"

CONFIG_PY = '''\
import os
import glob

# Relocatable loader config generated by make_wheel.py.
# OpenCV DLLs live next to the package; CUDA / cuDNN are searched on the system.
_dirs = [os.path.join(LOADER_DIR, "libs")]

_cuda_roots = [os.environ.get("CUDA_PATH")]
_cuda_roots += sorted(
    glob.glob(r"C:\\Program Files\\NVIDIA GPU Computing Toolkit\\CUDA\\v*"), reverse=True
)
for _root in _cuda_roots:
    if _root:
        _dirs += [os.path.join(_root, "bin", "x64"), os.path.join(_root, "bin")]

_cudnn = [os.environ.get("CUDNN_PATH")]
_cudnn_roots = [r for r in _cudnn if r]
_cudnn_roots += sorted(glob.glob(r"C:\\Program Files\\NVIDIA\\CUDNN\\v*"), reverse=True)
for _root in _cudnn_roots:
    _dirs += sorted(glob.glob(os.path.join(_root, "bin", "*", "x64")), reverse=True)
    _dirs += [os.path.join(_root, "bin")]

_seen = set()
BINARIES_PATHS = [
    d for d in _dirs
    if os.path.isdir(d) and not (d.lower() in _seen or _seen.add(d.lower()))
] + BINARIES_PATHS
'''

CONFIG_VER_PY = '''\
PYTHON_EXTENSIONS_PATHS = [
    os.path.join(LOADER_DIR, "python-{ver}")
] + PYTHON_EXTENSIONS_PATHS
'''


def sha256_b64(data: bytes) -> str:
    digest = hashlib.sha256(data).digest()
    return "sha256=" + base64.urlsafe_b64encode(digest).rstrip(b"=").decode("ascii")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--cv2-dir", required=True, type=Path, help="installed cv2 package directory")
    ap.add_argument("--bin-dir", required=True, type=Path, help="OpenCV install bin dir with the runtime DLLs")
    ap.add_argument("--out", required=True, type=Path, help="output directory for the wheel")
    ap.add_argument("--version", required=True, help="OpenCV version, e.g. 4.14.0")
    ap.add_argument("--cuda", default="", help="CUDA version label, e.g. 13.5")
    ap.add_argument("--name", default=DIST_NAME)
    args = ap.parse_args()

    cv2_dir: Path = args.cv2_dir
    bin_dir: Path = args.bin_dir
    if not (cv2_dir / "__init__.py").is_file():
        print(f"error: {cv2_dir} is not an installed cv2 package", file=sys.stderr)
        return 1
    dlls = sorted(bin_dir.glob("*.dll"))
    if not dlls:
        print(f"error: no DLLs found in {bin_dir}", file=sys.stderr)
        return 1

    # python tag from the extension module name: cv2.cp312-win_amd64.pyd
    pyds = list(cv2_dir.glob("python-*/cv2.*.pyd"))
    if not pyds:
        print(f"error: no cv2 *.pyd found under {cv2_dir}\\python-*", file=sys.stderr)
        return 1
    m = re.match(r"cv2\.(cp\d+)-(win_amd64|win32)\.pyd$", pyds[0].name)
    if not m:
        print(f"error: unexpected extension name {pyds[0].name}", file=sys.stderr)
        return 1
    py_tag, plat = m.group(1), m.group(2)
    py_ver = pyds[0].parent.name.split("-", 1)[1]  # "3.12"

    local = f"+cuda{args.cuda}" if args.cuda else ""
    version = f"{args.version}{local}"
    dist = args.name.replace("-", "_")
    dist_info = f"{dist}-{version}.dist-info"
    wheel_name = f"{dist}-{version}-{py_tag}-{py_tag}-{plat}.whl"

    args.out.mkdir(parents=True, exist_ok=True)
    wheel_path = args.out / wheel_name

    records: list[tuple[str, str, int]] = []

    with zipfile.ZipFile(wheel_path, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as zf:

        def add(arcname: str, data: bytes) -> None:
            zf.writestr(zipfile.ZipInfo(arcname, date_time=(2026, 1, 1, 0, 0, 0)), data, zipfile.ZIP_DEFLATED)
            records.append((arcname, sha256_b64(data), len(data)))

        # 1. the cv2 package (without caches and the absolute-path configs)
        skip = re.compile(r"^(config\.py|config-\d+(\.\d+)?\.py)$")
        for path in sorted(cv2_dir.rglob("*")):
            if not path.is_file() or "__pycache__" in path.parts or path.suffix == ".pyc":
                continue
            rel = path.relative_to(cv2_dir)
            if len(rel.parts) == 1 and skip.match(rel.name):
                continue
            add("cv2/" + rel.as_posix(), path.read_bytes())

        # 2. relocatable loader configs
        add("cv2/config.py", CONFIG_PY.encode("utf-8"))
        add(f"cv2/config-{py_ver}.py", CONFIG_VER_PY.format(ver=py_ver).encode("utf-8"))

        # 3. OpenCV runtime DLLs
        for dll in dlls:
            add("cv2/libs/" + dll.name, dll.read_bytes())

        # 4. dist-info
        metadata = (
            "Metadata-Version: 2.1\n"
            f"Name: {args.name}\n"
            f"Version: {version}\n"
            f"Summary: {SUMMARY}\n"
            f"Requires-Python: >={py_ver}\n"
            "Requires-Dist: numpy>=2\n"
            "Description-Content-Type: text/plain\n\n"
            f"OpenCV {args.version} with contrib modules, built with CUDA {args.cuda or '?'}.\n"
            "Provides the `cv2` module; uninstall opencv-python / opencv-contrib-python first.\n"
            "Needs the NVIDIA driver, the matching CUDA Toolkit runtime and (for cv2.dnn on CUDA) cuDNN\n"
            "installed on the machine; they are not bundled.\n"
        )
        add(f"{dist_info}/METADATA", metadata.encode("utf-8"))
        add(
            f"{dist_info}/WHEEL",
            (
                "Wheel-Version: 1.0\n"
                "Generator: make_wheel.py\n"
                "Root-Is-Purelib: false\n"
                f"Tag: {py_tag}-{py_tag}-{plat}\n"
            ).encode("utf-8"),
        )
        add(f"{dist_info}/top_level.txt", b"cv2\n")

        record_lines = [f"{n},{h},{s}" for n, h, s in records]
        record_lines.append(f"{dist_info}/RECORD,,")
        zf.writestr(
            zipfile.ZipInfo(f"{dist_info}/RECORD", date_time=(2026, 1, 1, 0, 0, 0)),
            "\n".join(record_lines) + "\n",
            zipfile.ZIP_DEFLATED,
        )

    size_mb = wheel_path.stat().st_size / (1024 * 1024)
    print(f"wheel: {wheel_path}  ({size_mb:.0f} MB, {len(dlls)} DLLs)")
    print(f"install with:  pip install --force-reinstall \"{wheel_path}\"")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
